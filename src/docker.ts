import { execFile } from "node:child_process";
import { appendFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { promisify } from "node:util";

import { findTool, resolveVersion, PINNED_IMAGE, type Manifest } from "./components.js";
import { CACHE_ROOT, STATE_ROOT } from "./paths.js";
import {
  RunError,
  execAttrs,
  execLogged,
  proxyFromEnv,
  runId,
  runsDir,
  validateProject,
  type RunRequest,
  type RunResult,
} from "./sandbox.js";
import { Span } from "./telemetry.js";

const execFileAsync = promisify(execFile);

// ---------------------------------------------------------------------------
// Docker mode for `run` — untrusted code in a throwaway container.
//   image   — the requested tool's pinned image (manifest docker=), digest only
//   mounts  — the project at /work; nothing else from the host
//   network — none by default; "proxy" = an internal per-run network whose only
//             exit is a forwarder container to the zero-trust proxy
//   limits  — no capabilities, no-new-privileges, your uid, cpu/memory/pids caps
// Colima must already be running; it is never started from here.
// ---------------------------------------------------------------------------

export type DockerNetwork = "none" | "proxy";

export interface DockerRunRequest extends RunRequest {
  network: DockerNetwork;
}

// Name of the @image line that pins the proxy forwarder.
const FORWARDER_IMAGE = "proxy-forwarder";
// Where the forwarder reaches the Mac's proxy from inside the Colima VM.
const HOST_FROM_VM = "host.lima.internal";

function dockerBin(): string {
  for (const d of (process.env.PATH || "").split(":").concat(["/opt/homebrew/bin", "/usr/local/bin"])) {
    if (d && existsSync(join(d, "docker"))) return join(d, "docker");
  }
  throw new RunError("docker CLI not found (expected Colima's docker in /opt/homebrew/bin)");
}

async function docker(args: string[], timeoutMs = 30_000): Promise<string> {
  const { stdout } = await execFileAsync(dockerBin(), args, { timeout: timeoutMs });
  return stdout.trim();
}

/** The single pinned image for this run, from the requested tool's manifest entry. */
function pickImage(m: Manifest, tools: Record<string, string>): { image: string; tool: string; version: string } {
  const names = Object.keys(tools);
  if (names.length !== 1) {
    throw new RunError(
      `docker mode runs one image, so pass exactly one tool (got ${names.length}). ` +
        `Build-tool images include their JDK, e.g. {"maven": ""} has Java 17.`,
    );
  }
  const def = findTool(m, names[0]);
  if (!def) throw new RunError(`Unknown component "${names[0]}"`);
  const v = resolveVersion(m, def, tools[names[0]]);
  if (!v.docker) {
    const withImage = m.versions.filter((x) => x.tool === def.name && x.docker).map((x) => x.version);
    throw new RunError(
      `${def.name} ${v.version} has no pinned docker image in the manifest` +
        (withImage.length ? `; versions with one: ${withImage.join(", ")}` : ""),
    );
  }
  if (!PINNED_IMAGE.test(v.docker)) throw new RunError(`refusing unpinned image ${v.docker}`);
  return { image: v.docker, tool: def.name, version: v.version };
}

/**
 * Remember every pinned image toolshelf runs. `components_images prune` (zsh)
 * removes only images in this list that the manifest no longer pins, so the
 * user's own images (e.g. node:22) are never touched.
 */
export const IMAGES_LOG = join(STATE_ROOT, "images.log");
function recordImage(ref: string): void {
  mkdirSync(STATE_ROOT, { recursive: true });
  const seen = existsSync(IMAGES_LOG) ? readFileSync(IMAGES_LOG, "utf-8").split("\n") : [];
  if (!seen.includes(ref)) appendFileSync(IMAGES_LOG, ref + "\n");
}

/** Maven ignores proxy env vars; give the container a settings.xml. */
function mavenSettings(port: string): string {
  const path = join(CACHE_ROOT, "docker", "m2-settings.xml");
  mkdirSync(join(CACHE_ROOT, "docker"), { recursive: true });
  writeFileSync(
    path,
    `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by toolshelf-mcp for docker-mode runs. Do not edit. -->
<settings>
  <proxies>
    <proxy><id>zt-https</id><active>true</active><protocol>https</protocol>
      <host>proxy</host><port>${port}</port><nonProxyHosts>localhost|127.0.0.1</nonProxyHosts></proxy>
    <proxy><id>zt-http</id><active>true</active><protocol>http</protocol>
      <host>proxy</host><port>${port}</port><nonProxyHosts>localhost|127.0.0.1</nonProxyHosts></proxy>
  </proxies>
</settings>
`,
  );
  return path;
}

export async function runDocker(m: Manifest, req: DockerRunRequest): Promise<RunResult> {
  const span = req.span ?? new Span("toolshelf.run");
  const project = validateProject(req.cwd);
  const { image, tool, version } = pickImage(m, req.tools);
  recordImage(image);
  span.set({ "container.image.name": image.split("@")[0] });

  await span.within("docker.check", async () => {
    try {
      await docker(["info", "--format", "{{.ServerVersion}}"], 10_000);
    } catch {
      throw new RunError("Docker isn't running. Start Colima yourself (`costart`); toolshelf never starts it.");
    }
  });

  const id = runId();
  span.set({ "toolshelf.run_id": id });
  const name = `toolshelf-${id}`;
  const net = `toolshelf-net-${id}`;
  const fwd = `toolshelf-fwd-${id}`;
  const logPath = join(runsDir(), `${id}.log`);

  const uid = process.getuid?.() ?? 501;
  const gid = process.getgid?.() ?? 20;
  const args = [
    "run", "--rm", "--quiet", "--name", name, "--pull", "missing",
    "--cap-drop", "ALL", "--security-opt", "no-new-privileges",
    "--pids-limit", "1024", "--memory", "4g", "--cpus", "2",
    "--user", `${uid}:${gid}`,
    "--tmpfs", "/tmp:rw,exec,size=2g",
    "-v", `${project}:/work`, "-w", "/work",
  ];
  // Your uid has no passwd entry in the image, and images keep tool homes in
  // root-owned dirs: point everything writable at /tmp (a fresh tmpfs per run).
  const env: Record<string, string> = {
    HOME: "/tmp",
    TOOLSHELF_SANDBOX: "docker",
    GRADLE_USER_HOME: "/tmp/.gradle",
    CARGO_HOME: "/tmp/.cargo",
    GOPATH: "/tmp/go",
    GOFLAGS: "-modcacherw",
    GOTOOLCHAIN: "local",
    MAVEN_CONFIG: "", // the maven image sets it, and mvn passes it on as an argument
    PIP_DISABLE_PIP_VERSION_CHECK: "1",
    // pnpm (e.g. via corepack in a node image): keep its dirs in the fresh /tmp
    PNPM_HOME: "/tmp/.pnpm",
    npm_config_store_dir: "/tmp/.pnpm-store",
  };
  const javaOpts = ["-Duser.home=/tmp"];

  let cleanup: string[][] = [];
  try {
    if (req.network === "proxy") {
      const forwarder = m.images[FORWARDER_IMAGE];
      if (!forwarder) {
        throw new RunError(`network "proxy" needs "@image ${FORWARDER_IMAGE} <image@sha256:…>" in the manifest`);
      }
      recordImage(forwarder);
      const port = proxyFromEnv().port;
      await span.within("docker.network_setup", async () => {
        await docker(["network", "create", "--internal", net]);
        cleanup.push(["network", "rm", net]);
        await docker([
          "run", "-d", "--rm", "--pull", "missing", "--name", fwd,
          "--network", net, "--network-alias", "proxy",
          "--cap-drop", "ALL", "--security-opt", "no-new-privileges",
          forwarder, `TCP-LISTEN:${port},fork,reuseaddr`, `TCP:${HOST_FROM_VM}:${port}`,
        ], 120_000);
        cleanup.unshift(["rm", "-f", fwd]);
        await docker(["network", "connect", "bridge", fwd]);
      });

      const p = `http://proxy:${port}`;
      args.push("--network", net);
      Object.assign(env, {
        http_proxy: p, https_proxy: p, HTTP_PROXY: p, HTTPS_PROXY: p,
        no_proxy: "localhost,127.0.0.1", NO_PROXY: "localhost,127.0.0.1",
        npm_config_proxy: p, npm_config_https_proxy: p, CARGO_HTTP_PROXY: p,
        MAVEN_ARGS: "-s /opt/toolshelf/m2-settings.xml",
      });
      for (const s of ["http", "https"]) javaOpts.push(`-D${s}.proxyHost=proxy`, `-D${s}.proxyPort=${port}`);
      // Not under /tmp: a bind there makes Docker create a root-owned /tmp/.m2
      args.push("-v", `${mavenSettings(port)}:/opt/toolshelf/m2-settings.xml:ro`);
    } else {
      args.push("--network", "none");
    }
    // Via MAVEN_OPTS/GRADLE_OPTS rather than JAVA_TOOL_OPTIONS, which makes every JVM
    // print a "Picked up JAVA_TOOL_OPTIONS" line.
    env.MAVEN_OPTS = env.GRADLE_OPTS = javaOpts.join(" ");
    for (const [k, v] of Object.entries(env)) args.push("-e", `${k}=${v}`);

    args.push("--entrypoint", "sh", image, "-c", req.command);

    // Includes pulling the image when it's missing (`--pull missing`).
    const r = await span.within("docker.exec", async (s) => {
      const r = await execLogged(dockerBin(), args, {
        cwd: project,
        env: process.env as Record<string, string>,
        timeoutSec: req.timeoutSec,
        tailChars: req.tailChars,
        logPath,
        header:
          `# toolshelf run ${id} (docker, network ${req.network})\n# cwd: ${project} → /work\n` +
          `# image: ${image}\n# command: ${req.command}\n`,
        onTimeout: () => {
          execFile(dockerBin(), ["kill", name], () => {});
        },
      });
      s.set(execAttrs(r));
      return r;
    });
    return { ...r, logPath, selected: [{ tool, version }] };
  } finally {
    if (cleanup.length) {
      await span.within("docker.cleanup", async () => {
        for (const c of cleanup) await docker(c).catch(() => {});
      });
    }
    cleanup = [];
  }
}
